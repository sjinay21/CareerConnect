export const addDummyJob = (job) => {
  dummyJobs = [job, ...dummyJobs];
};

export const removeDummyJob = (jobId) => {
  dummyJobs = dummyJobs.filter((job) => job.id != jobId);
};

export const applyToDummyJob = (jobId) => {
  const job = dummyJobs.find(j => j.id == jobId);
  if (job) {
    job.has_applied = true;
  }
};

export const formatSalary = (min, max) => {
  if (!min || !max) return "Not specified";
  const minLPA = min / 100000;
  const maxLPA = max / 100000;
  return `₹${minLPA} LPA - ₹${maxLPA} LPA`;
};
